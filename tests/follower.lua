local function setup(points,loop,start)
 local A={}; module('Store',A); module('Follower',A)
 return A.Follower.New({mapID=1,points=points,loop=loop},start or point(.09),distance,{arrival=15})
end
test('follower nearest join stable target gathering wait and one way completion',function()
 local f=setup({point(.1),point(.3)},false)
 eq(f:Snapshot().index,1); f:Tick(point(.2),0,false); eq(f:Snapshot().index,1)
 f:Tick(point(.1),1,true); eq(f:Snapshot().index,1)
 f:Tick(point(.1),2,false); eq(f:Snapshot().index,2)
 f:Tick(point(.3),5,false); eq(f:Snapshot().status,'complete'); eq(f:Target(),nil)
end)
test('follower overlapping and single point loops do not spin',function()
 local f=setup({point(.1),point(.1)},true)
 f:Tick(point(.1),0,false); for t=1,10 do f:Tick(point(.1),t,false) end; eq(f:Snapshot().index,2); eq(f:Snapshot().lap,0)
 local one=setup({point(.1)},true); for t=0,10 do one:Tick(point(.1),t,false) end; eq(one:Snapshot().lap,1)
end)
test('map loss suspends without advancing and manual pause survives return',function()
 local f=setup({point(.1),point(.3)},true)
 f:Tick(nil,0,false); eq(f:Snapshot().status,'suspended'); eq(f:Snapshot().index,1)
 f:Tick(point(.05),1,false); eq(f:Snapshot().status,'running')
 f:Pause(); f:Tick(nil,2,false); f:Tick(point(.1),3,false); eq(f:Snapshot().status,'paused'); eq(f:Snapshot().index,1)
 f:Resume(); f:Skip(); eq(f:Snapshot().index,2)
 f:Reverse(); eq(f:Snapshot().index,2); f:Skip(); eq(f:Snapshot().index,1)
end)
