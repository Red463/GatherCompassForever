local function setup(points,loop,start)
 local A={}; module('Store',A); module('Follower',A)
 return A.Follower.New({mapID=1,points=points,loop=loop},start or point(.09),distance,{arrival=15})
end

local function gatherPoint(x,key,id)
 local p=point(x);p.kind='gather';p.nodeKey=key;p.resourceKind='herb';p.materialID='gm:herb:'..(id or 402);p.name=id==401 and 'Peacebloom' or 'Silverleaf';return p
end
local function pickup(x,id,guid)
 local p=point(x);p.kind='herb';p.materialID='gm:herb:'..(id or 402);p.name=id==401 and 'Peacebloom' or 'Silverleaf';p.source='confirmed';p.sourceGUID=guid;return p
end
test('confirmed detour pickup skips the later stop for this lap and restores it next lap',function()
 local f=setup({gatherPoint(.1,'a'),gatherPoint(.3,'b'),gatherPoint(.5,'c')},true,point(.1))
 assert(f:ConfirmGather(pickup(.3)));eq(f.index,1);f:Tick(point(.1),0,false);eq(f.index,3)
 f:Tick(point(.5),1,false);eq(f.lap,1);eq(f.index,1);f:Tick(point(.1),2,false);eq(f.index,2)
end)
test('gather matching rejects visits imports wrong resource zone distant and conflicting objects',function()
 local f=setup({gatherPoint(.1,'a'),gatherPoint(.3,'b')},true)
 for _,o in ipairs({pickup(.3,401),pickup(.4),pickup(.3)}) do
  if o.x==.3 and o.materialID=='gm:herb:402' then o.mapID=2 end
  eq(f:ConfirmGather(o),nil)
 end
 local o=pickup(.3);o.source='imported';eq(f:ConfirmGather(o),nil);o.source=nil;eq(f:ConfirmGather(o),nil)
 f.route.points[2].objectID=123;o=pickup(.3);o.objectID=456;eq(f:ConfirmGather(o),nil)
 f:Tick(point(.1),1,false);eq(f.index,2)
end)
test('one physical gather consumes only its nearest spawn and duplicate loot cannot consume a neighbour',function()
