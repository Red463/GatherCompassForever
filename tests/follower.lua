local function setup(points,loop,start)
 local A={}; module('Store',A); module('Follower',A)
 return A.Follower.New({mapID=1,points=points,loop=loop},start or point(.09),distance,{arrival=15})
end
test('follower nearest join stable target gathering wait and one way completion',function()
 local f=setup({point(.1),point(.3)},false)
 eq(f:Snapshot().index,1); f:Tick(point(.2),0,false); eq(f:Snapshot().index,1)
 f:Tick(point(.1),1,true); eq(f:Snapshot().index,1)
 f:Tick(point(.1),2,false); eq(f:Snapshot().index,2)
 f:Tick(point(.3),5,false); eq(f:Snapshot().status,'complete'); eq(f:Target(),nil)
end)
test('follower overlapping and single point loops do not spin',function()
 local f=setup({point(.1),point(.1)},true)
 f:Tick(point(.1),0,false); for t=1,10 do f:Tick(point(.1),t,false) end; eq(f:Snapshot().index,2); eq(f:Snapshot().lap,0)
 local one=setup({point(.1)},true); for t=0,10 do one:Tick(point(.1),t,false) end; eq(one:Snapshot().lap,1)
end)

for _,elapsed in ipairs({.1,3}) do
 test('nearby waypoint respects arrival radius without extra approach at '..elapsed..' seconds',function()
  local f=setup({point(.1),point(.114),point(.3)},false,point(.1))
  f:Tick(point(.1),0,false);eq(f.index,2)
  f:Tick(point(.101),elapsed,false);eq(f.index,3)
 end)
end

test('distinct next waypoint can advance at the 15 yard boundary without a fixed delay',function()
 local f=setup({point(.1),point(.12),point(.3)},false,point(.1))
 f:Tick(point(.1),0,false);eq(f.index,2)
 f:Tick(point(.10500001),.1,false);eq(f.index,3)
end)

test('a nearby arrived waypoint still waits for gathering without requiring more movement afterward',function()
 local f=setup({point(.1),point(.114),point(.3)},false,point(.1))
 f:Tick(point(.1),0,false);f:Tick(point(.101),.1,true);eq(f.index,2)
 f:Tick(point(.101),.2,false);eq(f.index,3)
end)

test('nearby distinct loops require movement and coincident loops require leaving the radius',function()
 local f=setup({point(.1),point(.114)},true,point(.1))
 f:Tick(point(.1),0,false)
 for t=1,10 do f:Tick(point(.1),t,false) end;eq(f.index,2);eq(f.lap,0)
 f:Tick(point(.101),11,false);eq(f.lap,1)
 for t=12,20 do f:Tick(point(.101),t,false) end;eq(f.index,1);eq(f.lap,1)
 local one=setup({point(.1)},true,point(.114))
 one:Tick(point(.114),0,false);eq(one.lap,1)
 one:Tick(point(.121),1,false);one:Tick(point(.114),2,false);eq(one.lap,2)
end)

test('updating arrival distance preserves pause and overlap protection and validates values',function()
 local f=setup({point(.1),point(.114)},true,point(.1))
 f:Tick(point(.1),0,false);f:Pause();f:SetArrival(20);eq(f.arrival,20);eq(f.status,'paused')
 f:Resume();f:Tick(point(.1),3,false);eq(f.index,2)
 f:SetArrival(100);eq(f.arrival,40);f:SetArrival(0);eq(f.arrival,5)
 f:SetArrival(0/0);eq(f.arrival,15)
end)
test('map loss suspends without advancing and manual pause survives return',function()
 local f=setup({point(.1),point(.3)},true)
 f:Tick(nil,0,false); eq(f:Snapshot().status,'suspended'); eq(f:Snapshot().index,1)
 f:Tick(point(.05),1,false); eq(f:Snapshot().status,'running')
 f:Pause(); f:Tick(nil,2,false); f:Tick(point(.1),3,false); eq(f:Snapshot().status,'paused'); eq(f:Snapshot().index,1)
 f:Resume(); f:Skip(); eq(f:Snapshot().index,2)
 f:Reverse(); eq(f:Snapshot().index,2); f:Skip(); eq(f:Snapshot().index,1)
end)

test('generated loop joins the nearest point toward its shorter outgoing side',function()
 local A={};module('Store',A);module('Follower',A)
 local route={mapID=1,generated=true,loop=true,points={point(.1),point(.9),point(.12)}}
 local f=A.Follower.New(route,point(.1),distance);eq(f.index,1);eq(f.direction,-1)
 f:Tick(point(.1),0,false);eq(f.index,3)
end)
